function t(req, key, replacements) {
  // Onbekende taal: val terug op EN (breedst begrepen), daarna NL.
  let msg = (T[req?.lang || 'nl'] || T.en || T.nl)[key] || T.en?.[key] || T.nl[key] || key;
  if (replacements) {
    for (const [k, v] of Object.entries(replacements)) {
      msg = msg.replace(`{${k}}`, v);
    }
  }
  return msg;
}

